// Regenerates lib/canned.ts: one real model answer per landing chip.
// Run `npm run canned` (needs MISTRAL_API_KEY in .env.local). Re-run whenever
// lib/data/portfolio.ts, lib/few-shots.ts or the registry changes.
//
// Each answer is validated the way the client will consume it: it must not be
// truncated, must compile against portfolioRegistry, and must server-render.
// If any chip fails, nothing is written, so a half-refreshed file never ships.
import { writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { compile } from "@generative-semantic-ui/core";
import { portfolioRegistry } from "@/lib/adapter/registry";
import { generateJsx } from "@/lib/generate";
import { SUGGESTIONS } from "@/lib/suggestions";

const OUT = new URL("../lib/canned.ts", `file://${process.cwd()}/scripts/`);
const ATTEMPTS = 3;

async function answer(prompt: string, apiKey: string): Promise<string> {
  let last = "unknown";
  for (let i = 1; i <= ATTEMPTS; i++) {
    try {
      const out = await generateJsx(prompt, apiKey);
      if (out.truncated) throw new Error(`truncated: ${out.reason}`);
      const element = compile(out.jsx, portfolioRegistry);
      const html = renderToStaticMarkup(createElement("div", null, element));
      if (html.length < 50) throw new Error("rendered (almost) nothing");
      if (/mailto:|[\w.-]+@[\w-]+\.\w/.test(out.jsx)) {
        throw new Error("contains an email address");
      }
      return out.jsx;
    } catch (e) {
      last = e instanceof Error ? e.message : String(e);
      console.warn(`  attempt ${i}/${ATTEMPTS} failed: ${last}`);
    }
  }
  throw new Error(`"${prompt}": ${last}`);
}

async function main() {
  const apiKey = process.env.MISTRAL_API_KEY;
  if (!apiKey) throw new Error("MISTRAL_API_KEY is not set (apps/portfolio/.env.local)");

  const canned: Record<string, { jsx: string }> = {};
  for (const prompt of SUGGESTIONS) {
    console.log(`generating: ${prompt}`);
    canned[prompt] = { jsx: await answer(prompt, apiKey) };
  }

  const src = `// GENERATED by \`npm run canned\` (scripts/generate-canned.ts) — do not edit by hand.
// Real model output, validated against the registry. Refresh after changing
// lib/data/portfolio.ts, lib/few-shots.ts or the registry.
export const CANNED: Record<string, { jsx: string }> = ${JSON.stringify(canned, null, 2)};

export function getCanned(prompt: string): { jsx: string } | null {
  return CANNED[prompt.trim()] ?? null;
}
`;
  writeFileSync(OUT, src);
  console.log(`wrote ${Object.keys(canned).length} answers to lib/canned.ts`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
